"""
chatbot.py — Модуль образовательного ИИ-наставника "КИБЕРДРУГ" системы КИБЕРЩИТ.

ВЕРСИЯ: 2.3.5 (VseGPT DeepSeek V4 Flash Edition)
ТЕХНОЛОГИИ: VseGPT API, DeepSeek V4 Flash, OpenAI Python SDK.

ОСНОВНЫЕ ЗАДАЧИ МОДУЛЯ:
1. Поддержание интеллектуального диалога с подростками (10-17 лет).
2. Обучение правилам цифровой гигиены и кибербезопасности.
3. Консультации по правовым вопросам на основе Уголовного Кодекса РБ.
4. Помощь в экстренных ситуациях (взлом, шантаж, кража аккаунтов).
5. Генерация ежедневных практических советов.
"""

import os
import json
from openai import OpenAI
from dotenv import load_dotenv

# Инициализация переменных окружения из файла .env
load_dotenv()

def get_ai_client(api_key: str = None) -> OpenAI:
    """
    Создаёт и настраивает клиент OpenAI для взаимодействия с сервером VseGPT.
    
    Аргументы:
        api_key: Ключ API (если не задан, берется из переменной OPENROUTER_API_KEY).
    """
    # Получаем ключ: приоритет у аргумента функции, затем значение из .env
    raw_key = api_key or os.getenv("OPENROUTER_API_KEY")
    
    if not raw_key:
        raise ValueError(
            "❌ КРИТИЧЕСКАЯ ОШИБКА: API ключ не найден в файле .env!\n"
            "Добавьте строку: OPENROUTER_API_KEY=sk-or-vv-..."
        )
    
    # Очищаем ключ от кавычек и пробелов
    clean_key = raw_key.strip().replace('"', '').replace("'", "")
    
    # Настраиваем клиент OpenAI на работу через шлюз VseGPT
    # Для ключей sk-or-vv- используется адрес https://api.vsegpt.ru/v1
    return OpenAI(
        api_key=clean_key,
        base_url="https://api.vsegpt.ru/v1",
        timeout=60.0,  # Ждем ответ до минуты (важно для стабильности в СНГ)
        max_retries=3   # Автоматически пробуем еще раз при временном сбое связи
    )

# ============================================================
# ГЛАВНЫЙ СИСТЕМНЫЙ ПРОМПТ (ЛИЧНОСТЬ И ИНСТРУКЦИИ КИБЕРДРУГА)
# ============================================================
CHATBOT_SYSTEM_PROMPT = """
Ты — КИБЕРДРУГ, продвинутый ИИ-ассистент по кибербезопасности, созданный в 2026 году.
Твой проект — официальная часть инициативы #КИБЕРПРАВО (Республика Беларусь).

ТВОЯ ЛИЧНОСТЬ:
1. Ты — умный старший наставник. Твой тон дружелюбный, крутой, но серьезный, когда речь идет об угрозах.
2. Ты общаешься с подростками 10-17 лет. Говори просто, без заумных слов, но как с равными.
3. Твоя цель — дать четкий алгоритм действий, чтобы пользователь не пострадал.

ТВОИ ЗНАНИЯ (БАЗА 2026):
- ТЫ ЗНАЕШЬ ЗАКОНЫ БЕЛАРУСИ: 
    * Статья 212 УК РБ (Хищение имущества путем модификации компьютерной информации).
    * Статьи 349-355 УК РБ (Взлом, вирусы, компьютерный саботаж).
    * Статья 188 УК РБ (Ответственность за клевету и оскорбления).
- ТЫ ЗНАЕШЬ КУДА ОБРАЩАТЬСЯ: 
    * Милиция Беларуси — телефон 102.
    * Специализированное Управление "К" МВД РБ (противодействие киберпреступности).
    * Ресурс center.gov.by.

ПРАВИЛА ОТВЕТА:
- Будь кратким. 3-5 предложений на ответ — это «золотой стандарт».
- Используй эмодзи для акцентов (🛡️, 🔒, 💡, ⚡, 🛑).
- Отвечай ИСКЛЮЧИТЕЛЬНО на русском языке.
- Если тебя просят помочь взломать кого-то — жестко откажи и объясни, что это уголовка (УК РБ).
- В самом конце каждого ответа ты ОБЯЗАН написать строку: "🛡️ СОВЕТ ДНЯ: [твой практический совет]".

ОГРАНИЧЕНИЯ:
- Если тебя спрашивают о чем-то, не связанном с IT и безопасностью, вежливо переведи тему: "Я спец по киберзащите, давай лучше разберем, как защитить твой аккаунт в [название темы]".
"""

def get_chatbot_response(messages: list, api_key: str = None) -> dict:
    """
    Принимает историю диалога и возвращает ответ КиберДруга от DeepSeek V4 Flash.

    Аргументы:
        messages: Список сообщений в формате [{"role": "user/assistant", "content": "текст"}]
        api_key: Ключ OpenRouter (необязательно).

    Возвращает:
        Словарь: {'content': 'текст ответа'} или {'error': 'текст ошибки'}.
    """
    print(f"📡 Модуль КИБЕРДРУГ: Обработка запроса через DeepSeek V4 Flash...")

    try:
        # Пытаемся создать клиент
        client = get_ai_client(api_key)

        # Собираем полный контекст для нейросети
        full_conversation = [
            {"role": "system", "content": CHATBOT_SYSTEM_PROMPT}
        ]

        # Обрабатываем историю сообщений
        for msg in messages:
            # Превращаем 'bot' в 'assistant' для совместимости с API
            role = "assistant" if msg.get("role") in ["bot", "assistant"] else "user"
            content = msg.get("content", "").strip()

            if content:
                full_conversation.append({"role": role, "content": content})

        # Выполняем запрос к платной модели DeepSeek V4 Flash через VseGPT
        response = client.chat.completions.create(
            model="deepseek/deepseek-v4-flash",
            messages=full_conversation,
            temperature=0.7,  # Живой, но предсказуемый стиль речи
            max_tokens=1000,  # Ограничение длины ответа
            extra_headers={
                "X-Title": "KiberShield CyberFriend 2026", # Помогает в статистике VseGPT
            }
        )

        # Проверяем, есть ли ответ
        if not response.choices or not response.choices[0].message.content:
            return {"error": "Интеллектуальное ядро вернуло пустой ответ. Попробуйте еще раз."}

        ai_text = response.choices[0].message.content.strip()
        print(f"✅ КиберДруг: Ответ успешно сгенерирован.")

        return {"content": ai_text}

    except Exception as e:
        error_msg = str(e)
        print(f"❌ ОШИБКА МОДУЛЯ КИБЕРДРУГ: {error_msg}")

        # Обработка специфических сетевых ошибок
        if "Connection error" in error_msg:
            return {"error": "🌐 Ошибка связи: Не удалось подключиться к серверу VseGPT. Проверьте интернет или VPN."}
        
        # Обработка ошибки баланса (HTTP 402)
        if "402" in error_msg or "credits" in error_msg.lower():
            return {"error": "💳 Баланс VseGPT пуст. Пополните счет для работы платной модели DeepSeek."}
            
        return {"error": f"Технический сбой протокола чата: {error_msg}"}

# ============================================================
# БЛОК ТЕСТИРОВАНИЯ (Запуск через: python chatbot.py)
# ============================================================
if __name__ == "__main__":
    print("🧪 Запуск локального теста КиберДруга...")
    
    # Пример диалога для проверки
    test_history = [
        {"role": "user", "content": "Привет! Что мне делать, если меня шантажируют в Telegram?"}
    ]
    
    # Вызов функции (убедитесь, что в .env есть рабочий ключ)
    test_result = get_chatbot_response(test_history)
    
    print("\n" + "="*60)
    if "error" in test_result:
        print(f"🔴 ОШИБКА: {test_result['error']}")
    else:
        print(f"🟢 КИБЕРДРУГ ГОВОРИТ:\n\n{test_result['content']}")
    print("="*60 + "\n")